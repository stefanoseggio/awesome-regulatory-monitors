"""Python port of ``lib/_guards.ts``: the watchlist sanitiser every Master Engine applies before anything can match or bill.

The port is exact. ``tests/fixtures/guard_parity.json`` is generated by ``scripts/generate_distribution_data.ts`` from the
TypeScript guard itself, and ``tests/test_guard_parity.py`` asserts that this module reproduces every expected value
(keywords, needles, rejection reasons, the previews of rejected values and the one-line description) for every case.

Why the client needs it at all: a watchlist that sanitises to nothing must never be sent as if it were a filter. A
substring test against an empty needle is vacuously true, which is the root cause of the "ghost billing" incident the
TypeScript guard remediates (docs/apify_portfolio_refactor_strategy_2026.md, section 5). The engines sanitise again on
their side; sanitising here as well lets the caller see, before any run starts, that a watchlist would have been dropped.

Validation, per keyword and in this order:
    must be a string -> at most ``MAX_RAW_KEYWORD_UNITS`` UTF-16 units (checked before any Unicode work, because NFKC is quadratic
    on adversarial combining marks) -> well-formed Unicode (a lone surrogate is ``invalid_unicode``) -> cleaned to a fixed point of
    NFKC, whitespace controls to a space, every invisible character removed, whitespace runs collapsed and ends trimmed (a text with
    more than ``MAX_COMBINING_RUN`` consecutive combining marks is empty, tested before every pass's NFKC, and so is a text that NFKC
    expands to more than four times its length plus 16 units) -> at least ``MIN_KEYWORD_LENGTH`` code points after cleaning and at least
    that many visible code points BEFORE it (one glyph that NFKC expands, such as the circled number twenty, is one character) ->
    at least one letter or number (``no_letter_or_digit``) and at least TWO (``single_letter_or_digit``: ``c.``, ``a |`` and ``-0`` are the
    one-letter needle in disguise) -> at least 2 glyphs (letters, numbers, symbols) before NFKC (``too_short``: an expanding glyph plus punctuation is one
    character) -> at most ``MAX_KEYWORD_LENGTH`` -> case-insensitive de-duplication (first spelling wins) ->
    at most ``MAX_KEYWORDS`` accepted.
At most ``MAX_CANDIDATES`` entries are inspected, and the string entries inspected (those of ``MAX_RAW_KEYWORD_UNITS`` units or fewer;
a longer one is rejected at once and costs nothing) add up to at most ``MAX_TOTAL_RAW_UNITS`` UTF-16 units; the rest is reported as ONE
``over_limit`` entry. A bare string is first cut to ``MAX_BARE_STRING_UNITS`` UTF-16 units (never ending in half of a surrogate pair) and, if
that cut anything off, its last piece (which the cut may have truncated) is dropped and reported; then it is split on LF, CR, comma and semicolon.
``find_keyword_match`` searches a haystack of up to ``MAX_HAYSTACK_UNITS`` UTF-16 units whole; a longer one only up to the last Unicode
White_Space character inside that window (nothing is searched when the window has none). A haystack with a run of more than ``MAX_COMBINING_RUN``
combining marks is searched with the run cut to its first ``MAX_COMBINING_RUN`` marks (one hostile field must not hide a record); a KEYWORD with such a
run is rejected. ``find_keyword_match`` and ``describe_sanitization`` never raise, and ``find_keyword_match`` re-checks every needle (at least
``MIN_KEYWORD_LENGTH`` code points and two letters or numbers) and reads at most ``MAX_KEYWORDS`` of them.

What "invisible" means is NOT read from ``unicodedata``: JavaScript removes every Default_Ignorable_Code_Point and Bidi_Control
character plus the C0/C1 controls, and Python's tables can neither list those properties nor be trusted to equal Node's Unicode
version. The generator computes the code point ranges on Node and writes them to ``data/engines.json``; the expression below is built from them.

Consecutive combining marks are counted with ``unicodedata.category`` (a category starting with ``M`` is ``\\p{M}``), because Python has no property
escapes; see the Unicode-version note below. The White_Space characters come from engines.json too.

The cleaning pass is repeated until the text stops changing, so ``normalise_keyword`` is idempotent by construction: the value it returns is
a fixed point, and cleaning a fixed point returns it unchanged. Sanitising the keywords a sanitise returned therefore accepts every one
of them again and rejects nothing (``tests/test_guard_hardening.py`` pins this), which is why the client no longer cleans the list a second time.

Python's NFKC, lower-casing and letter-or-number tests come from ``unicodedata``, whose Unicode version (14.0 on Python 3.11, 15.0 on 3.12, 15.1 on 3.13)
differs from Node 22's (16.0). The two agree on every code point both assign; they differ only on characters assigned in a later version
(for marks: 93 code points on 3.11, 51 on 3.12 and 3.13 that Node 22 knows as combining marks), so a run of 17 of those is not seen on an older Python.
"""

from __future__ import annotations

import functools
import itertools
import re
import unicodedata
from dataclasses import dataclass
from typing import Any

from ._js import JS_WHITESPACE_CHARS, has_surrogate, js_includes, to_js_string, utf16_cut, utf16_length
from .registry import load_registry

MIN_KEYWORD_LENGTH = 2
MAX_KEYWORD_LENGTH = 200
MAX_KEYWORDS = 500
MAX_RAW_KEYWORD_UNITS = 4096
MAX_CANDIDATES = 5000
MAX_BARE_STRING_UNITS = 200000
MAX_HAYSTACK_UNITS = 8192
MAX_NORMALISE_PASSES = 8
MAX_COMBINING_RUN = 16
MAX_TOTAL_RAW_UNITS = 200000

REJECTION_REASONS = (
    "not_a_string",
    "empty_after_normalisation",
    "too_short",
    "too_long",
    "invalid_unicode",
    "no_letter_or_digit",
    "single_letter_or_digit",
    "duplicate",
    "over_limit",
)

_BARE_STRING_SEPARATORS = re.compile(r"[\n\r,;]+")
# Turned into a space BEFORE the removal below: tab, line feed, vertical tab, form feed, carriage return and NEL are C0/C1 controls the removal would
# otherwise delete and fuse the words around them; line and paragraph separator are whitespace the removal leaves alone (the TypeScript guard lists the same set).
_WHITESPACE_CONTROLS = re.compile("[\t\n\x0b\x0c\r\x85\N{LINE SEPARATOR}\N{PARAGRAPH SEPARATOR}]")
_WHITESPACE_RUN = re.compile("[" + re.escape(JS_WHITESPACE_CHARS) + "]+")


def _removed_expression(ranges: tuple[tuple[int, int], ...]) -> re.Pattern[str]:
    parts = (f"\\U{first:08x}" if first == last else f"\\U{first:08x}-\\U{last:08x}" for first, last in ranges)
    return re.compile("[" + "".join(parts) + "]")


# Every code point the TypeScript guard removes, from engines.json (C0/C1 controls, Default_Ignorable_Code_Point, Bidi_Control).
_INVISIBLE = _removed_expression(load_registry().limits.removed_ranges)
# The Unicode White_Space characters (all in the BMP), from engines.json: they cut a haystack longer than MAX_HAYSTACK_UNITS.
_WHITE_SPACE = frozenset(code for first, last in load_registry().limits.white_space_ranges for code in range(first, last + 1))

# What a log line must not carry: the removed code points above (controls, Default_Ignorable_Code_Point, Bidi_Control), the line and paragraph
# separators (log shippers split on them) and lone surrogates.
_PREVIEW_UNSAFE = re.compile(_INVISIBLE.pattern[:-1] + "\u2028\u2029\ud800-\udfff]")
_PREVIEW_LIMIT = 60
_UNREADABLE = "[unreadable value]"


@dataclass(frozen=True)
class RejectedKeyword:
    """A watchlist entry the guard refused. ``value`` is a log-safe, truncated rendering and is never used for matching."""

    value: str
    reason: str


@dataclass(frozen=True)
class SanitizedKeywordList:
    """The guard's result. ``keywords`` keep the caller's casing; ``needles`` are their lower-cased matching twins."""

    keywords: tuple[str, ...]
    needles: tuple[str, ...]
    rejected: tuple[RejectedKeyword, ...]
    malformed_container: bool

    def to_dict(self) -> dict[str, Any]:
        """The shape the TypeScript guard returns (camelCase), used by the parity tests."""
        return {
            "keywords": list(self.keywords),
            "needles": list(self.needles),
            "rejected": [{"value": item.value, "reason": item.reason} for item in self.rejected],
            "malformedContainer": self.malformed_container,
        }


def _code_point_length(text: str) -> int:
    return len(to_js_string(text))


def _preview(value: Any) -> str:
    """``preview`` of the TypeScript guard: a bounded, log-safe description of a rejected value. Never raises and never serialises.

    A string is cut to 57 UTF-16 units (never ending in half of a surrogate pair) plus ``...`` when it is longer than 60, and every control,
    invisible and lone surrogate character in the result becomes U+FFFD. Anything else is a constant tag: ``[null]``, ``[array]``,
    ``[object]``, ``[number]`` or ``[boolean]`` (JSON.stringify of a deeply nested value cost 7 ms per entry, 9 s for a 9 MB input, so the guard
    no longer serialises). A value that cannot even be classified is ``[unreadable value]``, as for a revoked Proxy in JavaScript.
    """
    try:
        return _preview_unchecked(value)
    except Exception:  # noqa: BLE001 - whatever a hostile value raises must not reach the caller
        return _UNREADABLE


def _preview_unchecked(value: Any) -> str:
    if isinstance(value, str):
        # More than 60 code points is more than 60 units, so only the head decides what is cut (a giant string is never encoded whole).
        text = value[: _PREVIEW_LIMIT + 1]
        shown = utf16_cut(text, _PREVIEW_LIMIT - 3) + "..." if utf16_length(text) > _PREVIEW_LIMIT else to_js_string(value)
        return _PREVIEW_UNSAFE.sub("\ufffd", to_js_string(shown))
    if value is None:
        return "[null]"
    if isinstance(value, (list, tuple)):
        return "[array]"
    if isinstance(value, bool):
        return "[boolean]"
    if isinstance(value, (int, float)):
        return "[number]"
    return "[object]"


def _is_mark(char: str) -> bool:
    """``/[\\p{M}\\uFF9E\\uFF9F]/u``: a combining mark (Mn, Mc, Me) or a halfwidth voiced sound mark, which NFKC turns into one (see ``_guards.ts``)."""
    return unicodedata.category(char).startswith("M") or char in "\uff9e\uff9f"


def _has_long_combining_run(text: str) -> bool:
    """``/[\\p{M}\\uFF9E\\uFF9F]{17}/u``: more than ``MAX_COMBINING_RUN`` consecutive combining marks (Mn, Mc, Me and U+FF9E/U+FF9F), counted by code point."""
    if text.isascii():
        return False
    run = 0
    for char in text:
        if _is_mark(char):
            run += 1
            if run > MAX_COMBINING_RUN:
                return True
        else:
            run = 0
    return False


def _cut_mark_runs(text: str) -> str:
    """``text.replace(/([\\p{M}\\uFF9E\\uFF9F]{16})[\\p{M}\\uFF9E\\uFF9F]+/gu, '$1')``: every run of combining marks keeps its first ``MAX_COMBINING_RUN`` marks."""
    out: list[str] = []
    run = 0
    for char in text:
        if _is_mark(char):
            run += 1
            if run > MAX_COMBINING_RUN:
                continue
        else:
            run = 0
        out.append(char)
    return "".join(out)


def _clean_once(text: str, hostile_runs: str) -> str:
    # Before NFKC: reordering a long run of marks is quadratic, and no real text contains one. A keyword with one is empty; a haystack keeps
    # the first MAX_COMBINING_RUN marks of the run, so one hostile field cannot hide a record.
    if _has_long_combining_run(text):
        if hostile_runs == "reject":
            return ""
        text = _cut_mark_runs(text)
    normalised = unicodedata.normalize("NFKC", text)
    # No real text grows 4x under NFKC; one that does (U+FDFA becomes 18 characters) is made to burn the cleaning passes.
    if utf16_length(normalised) > utf16_length(text) * 4 + 16:
        return ""
    text = _WHITESPACE_CONTROLS.sub(" ", normalised)
    text = _INVISIBLE.sub("", text)
    # Removing a character between two lone surrogate halves can make them an adjacent pair, which JavaScript reads as one character.
    text = to_js_string(text)
    text = _WHITESPACE_RUN.sub(" ", text)
    return text.strip(JS_WHITESPACE_CHARS)


def normalise_keyword(raw: str, hostile_runs: str = "reject") -> str:
    """Cleans ``raw`` until it stops changing: NFKC, whitespace controls to a space, invisible characters removed, whitespace runs collapsed, ends trimmed.

    Idempotent: ``normalise_keyword(normalise_keyword(x)) == normalise_keyword(x)``. A text that has not settled after ``MAX_NORMALISE_PASSES``
    passes (real text settles in at most 3) is hostile and becomes the empty string, which is never matched. The caller bounds the length first
    (``MAX_RAW_KEYWORD_UNITS``, ``MAX_HAYSTACK_UNITS``): normalisation is quadratic in the worst case. ``hostile_runs`` says what a run of more
    than ``MAX_COMBINING_RUN`` combining marks does: ``"reject"`` (keywords) makes the whole text empty, ``"cut"`` (haystacks) keeps the first
    ``MAX_COMBINING_RUN`` marks of the run.
    """
    current = to_js_string(raw)
    for _ in range(MAX_NORMALISE_PASSES):
        following = _clean_once(current, hostile_runs)
        if following == current:
            return following
        current = following
    return ""


def _count_letters_or_digits(text: str, at_least: int) -> int:
    """Letters and numbers (``[\\p{L}\\p{N}]``) in ``text``, counted up to ``at_least`` (then it stops)."""
    count = 0
    for ch in text:
        if unicodedata.category(ch)[0] in ("L", "N"):
            count += 1
            if count >= at_least:
                return count
    return count


def _count_glyphs(text: str, at_least: int) -> int:
    """Letters, numbers and symbols (``[\\p{L}\\p{N}\\p{S}]``) in ``text``, counted up to ``at_least``: what a reader counts as characters."""
    count = 0
    for ch in to_js_string(text):
        if unicodedata.category(ch)[0] in ("L", "N", "S"):
            count += 1
            if count >= at_least:
                return count
    return count


def _count_visible(text: str, at_least: int) -> int:
    """Code points of ``text`` that are neither removed as invisible nor White_Space, counted up to ``at_least``: the glyphs a reader sees."""
    count = 0
    for ch in to_js_string(text):
        if _INVISIBLE.match(ch) or ord(ch) in _WHITE_SPACE:
            continue
        count += 1
        if count >= at_least:
            return count
    return count


def _is_text(value: Any) -> bool:
    try:
        return isinstance(value, str)
    except Exception:  # noqa: BLE001 - an object whose __class__ raises is not a string we can read
        return False


def sanitize_keyword_list(value: Any) -> SanitizedKeywordList:
    """Turns whatever the caller sent for a watchlist into a clean list. Never raises; never returns an element that could match ``""``.

    Accepts a list or tuple of strings, or a single string split on newlines, commas and semicolons (never per
    character). ``None`` yields an empty result. Any other value yields an empty list with ``malformed_container=True``.
    A container that cannot be read at all (its length or iteration raises) disables the watchlist the same way, with one rejected
    entry ``[unreadable value]``.
    """
    try:
        return _sanitize(value)
    except Exception:  # noqa: BLE001 - a hostile in-process value must disable the watchlist, not the run
        return SanitizedKeywordList((), (), (RejectedKeyword(_UNREADABLE, "not_a_string"),), True)


def _sanitize(value: Any) -> SanitizedKeywordList:
    if value is None:
        return SanitizedKeywordList((), (), (), False)

    cut = False
    if isinstance(value, (list, tuple)):
        total = len(value)
        candidates: list[Any] = list(itertools.islice(value, MAX_CANDIDATES))
    elif isinstance(value, str):
        # More code points than the limit means more units than the limit, so a giant string is never encoded whole.
        cut = len(value) > MAX_BARE_STRING_UNITS or utf16_length(value) > MAX_BARE_STRING_UNITS
        pieces = _BARE_STRING_SEPARATORS.split(utf16_cut(value, MAX_BARE_STRING_UNITS))
        if cut:
            # The cut may have truncated the last piece ("Pfizer Inc" -> "Pfizer In"), which would be accepted as a different keyword: drop it.
            pieces.pop()
        total = len(pieces)
        candidates = pieces[:MAX_CANDIDATES]
    else:
        return SanitizedKeywordList((), (), (), True)

    keywords: list[str] = []
    needles: list[str] = []
    rejected: list[RejectedKeyword] = []
    seen: set[str] = set()
    inspected = 0
    total_units = 0
    for candidate in candidates:
        is_text = _is_text(candidate)
        too_long = False
        if is_text:
            # Only an entry that proceeds to Unicode work costs budget: one over the raw cap is rejected in constant time (and never encoded whole).
            units = len(candidate)
            if units <= MAX_RAW_KEYWORD_UNITS:
                units = utf16_length(candidate)
            too_long = units > MAX_RAW_KEYWORD_UNITS
            if not too_long:
                total_units += units
                if total_units > MAX_TOTAL_RAW_UNITS:
                    break
        inspected += 1
        if not is_text:
            rejected.append(RejectedKeyword(_preview(candidate), "not_a_string"))
            continue
        # Bounded BEFORE any Unicode work: normalisation is quadratic on adversarial combining marks.
        if too_long:
            rejected.append(RejectedKeyword(_preview(candidate), "too_long"))
            continue
        # Halves held as two code points are one astral character in JavaScript; after merging them, any surrogate left is lone.
        if has_surrogate(to_js_string(candidate)):
            rejected.append(RejectedKeyword(_preview(candidate), "invalid_unicode"))
            continue
        cleaned = normalise_keyword(candidate)
        if len(cleaned) == 0:
            rejected.append(RejectedKeyword(_preview(candidate), "empty_after_normalisation"))
            continue
        length = _code_point_length(cleaned)
        if length < MIN_KEYWORD_LENGTH:
            rejected.append(RejectedKeyword(_preview(candidate), "too_short"))
            continue
        # One glyph that NFKC expands (a circled number, the numero sign, a ligature) is one character typed, not two.
        if _count_visible(candidate, MIN_KEYWORD_LENGTH) < MIN_KEYWORD_LENGTH:
            rejected.append(RejectedKeyword(_preview(candidate), "too_short"))
            continue
        letters_or_digits = _count_letters_or_digits(cleaned, 2)
        if letters_or_digits == 0:
            rejected.append(RejectedKeyword(_preview(candidate), "no_letter_or_digit"))
            continue
        # One letter or digit padded with punctuation ("c.", "a |", "-0") matches almost everything: the one-letter needle in disguise.
        if letters_or_digits == 1:
            rejected.append(RejectedKeyword(_preview(candidate), "single_letter_or_digit"))
            continue
        # One expanding glyph padded with punctuation ("circled twenty" + a full stop) is still one character typed.
        if _count_glyphs(candidate, MIN_KEYWORD_LENGTH) < MIN_KEYWORD_LENGTH:
            rejected.append(RejectedKeyword(_preview(candidate), "too_short"))
            continue
        if length > MAX_KEYWORD_LENGTH:
            rejected.append(RejectedKeyword(_preview(candidate), "too_long"))
            continue
        needle = cleaned.lower()
        if needle in seen:
            rejected.append(RejectedKeyword(_preview(candidate), "duplicate"))
            continue
        if len(keywords) >= MAX_KEYWORDS:
            rejected.append(RejectedKeyword(_preview(candidate), "over_limit"))
            continue
        seen.add(needle)
        keywords.append(cleaned)
        needles.append(needle)
    if total > inspected:
        rejected.append(RejectedKeyword(f"({total - inspected} further entries not inspected)", "over_limit"))
    if cut:
        rejected.append(RejectedKeyword(f"(bare string cut at {MAX_BARE_STRING_UNITS} units; its last entry was dropped)", "over_limit"))
    return SanitizedKeywordList(tuple(keywords), tuple(needles), tuple(rejected), False)


def _cut_haystack(haystack: str) -> str:
    """``cutHaystack`` of the TypeScript guard: the part of a haystack that is searched.

    A haystack of ``MAX_HAYSTACK_UNITS`` UTF-16 units or fewer is searched whole. A longer one is searched only up to the LAST Unicode White_Space
    character inside that window (the character at unit ``end`` for the largest ``end`` of at most ``MAX_HAYSTACK_UNITS``; nothing composes across
    whitespace, so what is searched is a prefix of what the whole text cleans to); a window without any whitespace is not searched at all (``""``).
    The test is by UTF-16 unit, like ``String.prototype.charAt``, and the White_Space set comes from engines.json.
    """
    head = haystack[: MAX_HAYSTACK_UNITS + 1] if len(haystack) > MAX_HAYSTACK_UNITS else haystack
    data = head.encode("utf-16-le", "surrogatepass")
    if len(haystack) <= MAX_HAYSTACK_UNITS and len(data) <= 2 * MAX_HAYSTACK_UNITS:
        return haystack
    for end in range(MAX_HAYSTACK_UNITS, 0, -1):
        if int.from_bytes(data[2 * end : 2 * end + 2], "little") in _WHITE_SPACE:
            return data[: 2 * end].decode("utf-16-le", "surrogatepass")
    return ""


def find_keyword_match(haystack: Any, keyword_list: SanitizedKeywordList) -> str | None:
    """The first accepted keyword found in ``haystack`` (case-insensitive, NFKC-normalised substring match over UTF-16 units), or ``None``. Never raises.

    An empty list never matches, an empty or non-string haystack never matches, and a needle that is not a string of at most 400 units with at least
    ``MIN_KEYWORD_LENGTH`` code points and two letters or numbers, no lone surrogate and no NUL is skipped (a hand-built list cannot match ``".."`` or half
    of an astral character), exactly as the TypeScript guard does. At most ``MAX_KEYWORDS`` needles are read. A haystack of more than ``MAX_HAYSTACK_UNITS`` UTF-16 units is searched only up to the last whitespace
    character inside that window, cut before cleaning (see ``_cut_haystack``); a run of more than ``MAX_COMBINING_RUN`` combining marks in the
    searched text is cut to its first ``MAX_COMBINING_RUN`` marks. A haystack that NFKC would grow past four times its length plus 16 units is searched in pieces
    around the code points that expand more than four times (see ``_clean_haystack``) instead of being empty.
    """
    try:
        return _find_unchecked(haystack, keyword_list)
    except Exception:  # noqa: BLE001 - a malformed or hostile list matches nothing and bills nothing
        return None


_PIECE_SEPARATOR = "\x00"


def _split_at_heavy_expanders(text: str) -> list[str] | None:
    """The text split at every code point whose NFKC form is more than four times as long (in UTF-16 units) as it is, or ``None`` when it has none."""
    pieces: list[str] = []
    current: list[str] = []
    found = False
    for ch in to_js_string(text):
        if utf16_length(unicodedata.normalize("NFKC", ch)) > utf16_length(ch) * 4:
            found = True
            pieces.append("".join(current))
            current = []
        else:
            current.append(ch)
    if not found:
        return None
    pieces.append("".join(current))
    return pieces


def _clean_haystack(raw: str) -> str:
    """``cleanHaystack`` of the TypeScript guard: a text NFKC would grow past the cap is not emptied as a whole; the heavy expanders are cut out, the pieces
    between them are cleaned on their own and joined with NUL (no keyword contains it, so nothing matches across a cut-out character)."""
    whole = normalise_keyword(raw, "cut")
    if whole != "":
        return whole
    pieces = _split_at_heavy_expanders(raw)
    if pieces is None:
        return ""
    return _PIECE_SEPARATOR.join(piece for piece in (normalise_keyword(piece, "cut") for piece in pieces) if piece != "")


def _is_usable_needle(needle: Any) -> bool:
    """The sanitiser's floor again for a hand-built list, without anything that could match half of a character or cross a cut."""
    if not isinstance(needle, str):
        return False
    # JavaScript reads two separate surrogate halves that follow each other as the one character they form: so does every check below.
    seen = to_js_string(needle)
    return (
        utf16_length(seen) <= 2 * MAX_KEYWORD_LENGTH
        and _PIECE_SEPARATOR not in seen
        and not has_surrogate(seen)
        and _code_point_length(seen) >= MIN_KEYWORD_LENGTH
        and _count_letters_or_digits(seen, 2) >= 2
    )


@functools.lru_cache(maxsize=128)
def _usable_needle_indexes(needles: tuple[str | None, ...]) -> tuple[int, ...]:
    """Indexes of the usable needles of a tuple of strings (``None`` stands for an element that is not one), found once per distinct tuple (a run asks for every row)."""
    return tuple(index for index, needle in enumerate(needles) if needle is not None and _is_usable_needle(needle))


def _find_unchecked(haystack: Any, keyword_list: SanitizedKeywordList) -> str | None:
    if len(keyword_list.needles) == 0:
        return None
    if not isinstance(haystack, str) or len(haystack) == 0:
        return None
    text = _clean_haystack(_cut_haystack(haystack)).lower()
    if len(text) == 0:
        return None
    # One snapshot of the first MAX_KEYWORDS needles: it is what is checked and what is matched, and it is all that is hashed (a list of a million
    # needles costs no more than one of 500). An element that is not a string cannot be a needle and is never hashed, so it cannot break the cache key.
    needles = list(keyword_list.needles[:MAX_KEYWORDS])
    for index in _usable_needle_indexes(tuple(needle if isinstance(needle, str) else None for needle in needles)):
        needle = needles[index]
        if js_includes(text, needle):
            keyword = keyword_list.keywords[index] if index < len(keyword_list.keywords) else needle
            return keyword if isinstance(keyword, str) else needle
    return None


def describe_sanitization(keyword_list: SanitizedKeywordList, field_name: str = "watchlistNames") -> str:
    """One-line, log-safe description of what the guard did to the caller's list. Never raises."""
    try:
        return _describe_unchecked(keyword_list, field_name)
    except Exception:  # noqa: BLE001 - an unreadable list disables the watchlist, it does not stop the run
        return f"{field_name}: unreadable keyword list; watchlist disabled."


def _describe_unchecked(keyword_list: SanitizedKeywordList, field_name: str) -> str:
    if keyword_list.malformed_container:
        return f"{field_name}: unsupported value type; watchlist disabled (0 keywords)."
    if len(keyword_list.rejected) == 0:
        return f"{field_name}: {len(keyword_list.keywords)} keyword(s) accepted."
    by_reason: dict[str, int] = {}
    for item in keyword_list.rejected:
        by_reason[item.reason] = by_reason.get(item.reason, 0) + 1
    detail = ", ".join(f"{reason}={count}" for reason, count in by_reason.items())
    return f"{field_name}: {len(keyword_list.keywords)} accepted, {len(keyword_list.rejected)} rejected ({detail})."


def is_supplied(value: Any) -> bool:
    """True when the caller passed something: anything but ``None`` or an empty string, list, tuple, dict or set.

    A value that cannot be inspected (its length raises) counts as supplied: the caller meant something, so the client warns or refuses
    instead of running unfiltered.
    """
    try:
        if value is None:
            return False
        if isinstance(value, (str, list, tuple, dict, set, frozenset)):
            return len(value) > 0
        return True
    except Exception:  # noqa: BLE001 - fail closed
        return True
